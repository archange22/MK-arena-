-- MK Arena dedicated database schema.
-- Apply only to the new MK Arena Supabase project, never to kova-db.
-- The Discord bot uses the server-side service-role key; do not expose it to clients.
-- RLS is enabled without end-user policies so public/anon/authenticated clients cannot
-- read or mutate these bot tables. The trusted server-side service role bypasses RLS.

create table if not exists public.mk_warnings (
  id bigint generated by default as identity primary key,
  guild_id bigint not null,
  user_id bigint not null,
  moderator_id bigint not null,
  reason text not null,
  created_at timestamptz not null default now()
);

create index if not exists mk_warnings_guild_user_created_idx
  on public.mk_warnings (guild_id, user_id, created_at desc);

create table if not exists public.mk_guild_settings (
  guild_id bigint primary key,
  welcome_channel_id bigint,
  log_channel_id bigint,
  welcome_enabled boolean not null default true,
  xp_enabled boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.mk_user_xp (
  guild_id bigint not null,
  user_id bigint not null,
  xp bigint not null default 0 check (xp >= 0),
  level integer not null default 0 check (level >= 0),
  last_message_at double precision not null default 0,
  primary key (guild_id, user_id)
);

create index if not exists mk_user_xp_leaderboard_idx
  on public.mk_user_xp (guild_id, xp desc, level desc);

create table if not exists public.mk_tickets (
  id bigint generated by default as identity primary key,
  guild_id bigint not null,
  user_id bigint not null,
  channel_id bigint not null,
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now()
);

create index if not exists mk_tickets_guild_user_status_idx
  on public.mk_tickets (guild_id, user_id, status);

alter table public.mk_warnings enable row level security;
alter table public.mk_guild_settings enable row level security;
alter table public.mk_user_xp enable row level security;
alter table public.mk_tickets enable row level security;

comment on schema public is 'MK Arena dedicated Supabase project: bot tables use the mk_ prefix.';
